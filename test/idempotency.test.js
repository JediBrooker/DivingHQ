test("httpMiddleware: cache miss → next(); response captured on the way out", async () => {
  const pool = makePool();
  pool.enqueue({ rows: [] });           // lookup: not found
  pool.enqueue({ rows: [], rowCount: 0 });  // insert: ON CONFLICT DO NOTHING returns 0
  const idem = createIdempotency({ pool });
  const key = "a3f1c8d2-4b6e-4a8f-9d2c-1e3f5a7b9c0d";
  const { req, res } = makeMockReqRes({
    headers: { "X-Idempotency-Key": key },
    body: { score: 8.0 },
    user: { id: "u1" },
  });
  let nextCalled = false;
  await idem.httpMiddleware("submit_score")(req, res, () => { nextCalled = true; });
  assert.ok(nextCalled);

  // Handler responds.
  res.json({ ok: true, id: "score-123" });
  // Cache write is fire-and-forget; await a microtask for it to land.
  await new Promise((r) => setImmediate(r));
  assert.equal(pool.calls.length, 2);
  assert.ok(pool.calls[0].sql.startsWith("SELECT"));
  assert.ok(pool.calls[1].sql.startsWith("INSERT"));
  assert.equal(pool.calls[1].params[0], key);
  assert.equal(pool.calls[1].params[1], "u1");
  assert.equal(pool.calls[1].params[2], "submit_score");
});

test("httpMiddleware: cache hit, same user, same payload → replay", async () => {
  const cachedHash = hashPayload({ score: 8.0 });
  const pool = makePool();
  pool.enqueue({
    rows: [{
      user_id: "u1",
      request_hash: cachedHash,
      response_status: 200,
      response_body: { ok: true, id: "score-123" },
    }],
  });
  const idem = createIdempotency({ pool });
  const { req, res } = makeMockReqRes({
    headers: { "X-Idempotency-Key": "a3f1c8d2-4b6e-4a8f-9d2c-1e3f5a7b9c0d" },
    body: { score: 8.0 },
    user: { id: "u1" },
  });
  let nextCalled = false;
  await idem.httpMiddleware("submit_score")(req, res, () => { nextCalled = true; });
  assert.ok(!nextCalled);
  assert.equal(res.statusCode, 200);
  assert.deepEqual(res.sentBody, { ok: true, id: "score-123" });
  assert.equal(res.setHeaders["X-Idempotent"], "replay");
});

