// ---- Sweeper --------------------------------------------------

test("sweeper.sweep deletes rows older than 72 hours", async () => {
  const pool = makePool();
  pool.enqueue({ rowCount: 5 });
  // Re-init the sweeper's pool by calling start() then stop().
  // We don't want the interval running during the test, so call
  // stop() immediately after.
  sweeper.start({ pool, intervalMs: 999999999 });
  sweeper.stop();
  // The start() call also fires an initial sweep; that consumed
  // our queue entry. Re-queue + sweep manually for the assertion.
  pool.enqueue({ rowCount: 5 });
  const deleted = await sweeper.sweep();
  // Two sweep calls happened (one from start, one manual). Both
  // returned 5; we assert the manual one.
  assert.equal(deleted, 5);
  // Check the DELETE SQL shape.
  const lastCall = pool.calls[pool.calls.length - 1];
  assert.ok(lastCall.sql.includes("DELETE FROM idempotency_keys"));
  assert.ok(lastCall.sql.includes("created_at <"));
  assert.equal(lastCall.params[0], "72");
});

test("sweeper.start is idempotent", () => {
  const pool = makePool();
  pool.enqueue({ rowCount: 0 });
  sweeper.start({ pool, intervalMs: 999999999 });
  // Second start() should not throw or schedule again.
  sweeper.start({ pool, intervalMs: 999999999 });
  sweeper.stop();
  // We can't directly assert "only one interval registered" without
  // poking internals, but the lack of an error is the contract.
});
